# Main
# ---------------------------------------------------------------------------

def main() -> None:
    parser = argparse.ArgumentParser(description="Module 4: 3D Reconstruction (TRELLIS)")
    parser.add_argument("--input-manifest", required=True,
                        help="Path to recognize_manifest.json from Module 2")
    parser.add_argument("--scene-image", default=None,
                        help="Scene image for TRELLIS1 (defaults to manifest image)")
    parser.add_argument("--output-dir", required=True, help="Output directory")
    parser.add_argument("--trellis-version", choices=["1", "2"], default="1",
                        help="TRELLIS version (1 or 2)")
    parser.add_argument("--max-faces", type=int, default=0,
                        help="Max faces per mesh (0 = no decimation, e.g. 10000)")
    args = parser.parse_args()

    output_dir = os.path.abspath(args.output_dir)
    os.makedirs(output_dir, exist_ok=True)

    # Read recognize manifest
    with open(args.input_manifest, "r", encoding="utf-8") as f:
        rec_manifest = json.load(f)

    scene_image = args.scene_image or rec_manifest["image"]
    print(f"{TAG} Input manifest: {args.input_manifest}")
    print(f"{TAG} TRELLIS version: {args.trellis_version}")
    print(f"{TAG} Max faces: {args.max_faces if args.max_faces > 0 else 'unlimited'}")
    print(f"{TAG} {len(rec_manifest['objects'])} objects to reconstruct")

    # Run reconstruction
    if args.trellis_version == "1":
        results = reconstruct_trellis1(rec_manifest, scene_image, output_dir,
                                       max_faces=args.max_faces)
    else:
        results = reconstruct_trellis2(rec_manifest, output_dir,
                                       max_faces=args.max_faces)

    # Build manifest
    obj_entries = []
    for obj in rec_manifest["objects"]:
        name = obj["name"]
        r = results.get(name)
        if r and r.get("mesh_path"):
            entry = {
                "name": name,
                "glb_path": r["glb_path"],
                "mesh_path": r["mesh_path"],
                "vertices_count": r["vertices_count"],
                "faces_count": r["faces_count"],
                "has_colors": r.get("has_colors", False),
            }
            if r.get("canonical_glb_path"):
                entry["canonical_glb_path"] = r["canonical_glb_path"]
            if r.get("checkpoint_path"):
                entry["checkpoint_path"] = r["checkpoint_path"]
            obj_entries.append(entry)

    manifest = {
        "trellis_version": args.trellis_version,
        "objects": obj_entries,
    }
    manifest_path = os.path.join(output_dir, "reconstruction_3d_manifest.json")
    with open(manifest_path, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2)

    success = len(obj_entries)
    total = len(rec_manifest["objects"])
    print(f"\n{TAG} Done: {success}/{total} objects reconstructed")
    print(f"{TAG} Manifest: {manifest_path}")


if __name__ == "__main__":
    main()
